"""Derive compact per-area dish knowledge from the read-only food asset.

Counts venues whose NAME contains a dish name. This is a name signal only: it is
never menu, price or opening evidence. Output is a small generated TS module so
the app and local AI never scan the 90 MB database at generation time.
"""
import argparse
import hashlib
import json
import pathlib
import re
import sqlite3
import unicodedata

ROOT = pathlib.Path(__file__).resolve().parents[1]
MIN_AREA_VENUES = 100  # District-level areas only; ward names are ambiguous across districts.


def fold(value):
    value = unicodedata.normalize("NFD", value.lower().replace("đ", "d").replace("Đ", "d"))
    return re.sub(r"\s+", " ", "".join(c for c in value if unicodedata.category(c) != "Mn")).strip()


def compile_dishes(spec):
    dishes = {}
    for dish_id, item in spec["dishes"].items():
        if not re.fullmatch(r"[a-z]+(?:-[a-z]+)*", dish_id) or not item["names"]:
            raise ValueError("Invalid dish spec: " + dish_id)
        accented = [unicodedata.normalize("NFC", n.lower()) for n in item["names"]]
        ascii_names = [fold(n) for n in item["ascii"]]
        if any(re.search(r"[^\x00-\x7f]", n) for n in ascii_names):
            raise ValueError("ASCII alias is not ASCII: " + dish_id)
        dishes[dish_id] = {
            "accented": [re.compile(r"(?<!\w)" + re.escape(n) + r"(?!\w)") for n in accented],
            "ascii": [re.compile(r"(?<![a-z0-9])" + re.escape(n) + r"(?![a-z0-9])") for n in ascii_names],
            "aliases": sorted({fold(n) for n in item["names"] + item["ascii"]}),
        }
    return dishes


def dishes_in_name(name, dishes):
    """Accented names match accented aliases only, so 'Phố' never counts as 'phở'."""
    text = unicodedata.normalize("NFC", name.lower())
    key = "accented" if re.search(r"[^\x00-\x7f]", text) else "ascii"
    spans = {}
    for dish_id, dish in dishes.items():
        found = [m.span() for p in dish[key] for m in p.finditer(text)]
        if found:
            spans[dish_id] = found
    # Longest name wins: 'bún chả cá' is bun-ca, not also bun-cha.
    result = set()
    for dish_id, own in spans.items():
        covered = all(any(o != (s, e) and o[0] <= s and e <= o[1] and (o[1] - o[0]) > (e - s) for other, theirs in spans.items() if other != dish_id for o in theirs) for s, e in own)
        if not covered:
            result.add(dish_id)
    return result


def build(database, spec_path):
    spec = json.loads(pathlib.Path(spec_path).read_text(encoding="utf-8"))
    dishes = compile_dishes(spec)
    db = sqlite3.connect(f"file:{pathlib.Path(database).resolve().as_posix()}?mode=ro", uri=True)
    try:
        release = json.loads(db.execute("SELECT value FROM metadata WHERE key='manifest'").fetchone()[0])["release"]
        area_totals = {a: n for a, n in db.execute("SELECT area, count(*) FROM venue_areas GROUP BY area") if n >= MIN_AREA_VENUES and not a.startswith(("phuong ", "xa "))}
        areas_by_key = {}
        for area, key in db.execute("SELECT area, venue_key FROM venue_areas"):
            if area in area_totals:
                areas_by_key.setdefault(key, []).append(area)
        counts = {d: {"total": 0, "areas": {}} for d in dishes}
        closed = "lower(replace(coalesce(status,''),' ','_')) NOT IN ('permanently_closed','closed')"
        for key, name in db.execute(f"SELECT key, name FROM venues WHERE {closed}"):
            for dish_id in dishes_in_name(name, dishes):
                counts[dish_id]["total"] += 1
                for area in areas_by_key.get(key, []):
                    counts[dish_id]["areas"][area] = counts[dish_id]["areas"].get(area, 0) + 1
    finally:
        db.close()
    knowledge = {
        "release": release,
        "database_sha256": hashlib.sha256(pathlib.Path(database).read_bytes()).hexdigest(),
        "evidence": "venue_name_signal",
        "areaTotals": dict(sorted(area_totals.items())),
        "dishes": {d: {"aliases": dishes[d]["aliases"], "total": c["total"], "areas": dict(sorted(c["areas"].items()))} for d, c in counts.items()},
    }
    return knowledge


def write_module(knowledge, output):
    body = json.dumps(knowledge, ensure_ascii=False, indent=1)
    text = ("// GENERATED by scripts/build-food-knowledge.py from the bundled food asset. Do not edit.\n"
            "// Counts venues whose name contains a dish name; never menu, price or opening-hours evidence.\n"
            f"export const FOOD_KNOWLEDGE = {body} as const;\n")
    pathlib.Path(output).write_text(text, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--database", default=ROOT / "assets/food/sovi-food-2026-09-23.1.db")
    parser.add_argument("--spec", default=ROOT / "scripts/food-dishes.json")
    parser.add_argument("--output", default=ROOT / "src/food-knowledge.generated.ts")
    args = parser.parse_args()
    data = build(args.database, args.spec)
    write_module(data, args.output)
    print(json.dumps({d: v["total"] for d, v in data["dishes"].items()}, ensure_ascii=False))
